# 문체 고정용 few-shot 예시(CH019). 위치를 언급하지 않고 재질/색상/형태만 객관적으로
# 서술한 뒤 "~이 확인됩니다"로 끝맺는 패턴 — 실제 화면 산출물 예시에서 그대로 가져왔다.
#
# hotfix/472: 원래 예시 2개가 전부 "원단"이라는 단어를 직접 썼다("주변 원단보다...",
# "원단이 짧게 해지고...") — 지시문에서 "원단·배경 언급하지 말라"고 해도 few-shot이
# 지시문보다 스타일에 훨씬 강하게 작용해서 실제로는 "흰색 원단 위에" 식으로 계속 나왔다.
# 예시 자체에서 "원단"이라는 단어를 빼서 근본 원인을 없앤다.
_FEW_SHOT_EXAMPLES: tuple[str, ...] = (
    "주변보다 갈색빛이 도는 색상 차이가 확인됩니다.",
    "짧게 해지고 올이 드러난 영역이 확인됩니다.",
)


def build_defect_prompt(defect_label: str) -> str:
    """하자 라벨(한글) -> VLM에게 줄 프롬프트 텍스트. 위치는 절대 묻지 않는다.

    앞부분에 few-shot 예시로 답변 문체를 보여주고, 이어서 기존 지시문(위치 언급 금지·
    한 문장·지어내지 않기)을 그대로 유지한다.

    2026-08-06(`AI/validation/QUAL/vlm-description-check/`에서 배치 방식 검증 중 발견):
    지시문이 "색상·모양·크기·질감 등"을 전부 나열하라고 요구했는데, few-shot 예시는 특징
    하나만 짧게 말한다 — 예시와 지시문의 "요구 범위"가 어긋나서 모델이 체크리스트를
    채우려는 듯 장황해지는 경향이 실측됐다. 예시처럼 한 가지만 짧게 요구하도록 고쳤다.
    """
    examples = "\n".join(f"- {example}" for example in _FEW_SHOT_EXAMPLES)
    return (
        "아래는 하자 시각 설명의 좋은 답변 예시입니다.\n"
        f"{examples}\n\n"
        f"이 이미지는 중고 의류의 '{defect_label}' 하자 부분을 확대한 사진입니다. "
        "옷의 어느 부위인지는 추측하거나 언급하지 마세요. "
        "허리, 소매, 목깃, 밑단처럼 옷의 부위를 가리키는 단어는 어떤 경우에도 쓰지 마세요 — "
        "위치(Finding.section)는 이미 별도로 표시되니 여기서 다시 등장할 이유가 없는 단어입니다. "
        "'흰색 원단 위에', '옷감 위에'처럼 배경 원단·색상을 다시 언급하지 말고, 하자 자체의 "
        "시각적 특징만 말하세요 — 원단 배경도 이미 별도로 표시되므로 여기서 반복할 필요가 "
        "없습니다. "
        "위 예시처럼 사진에서 가장 눈에 띄는 시각적 특징 딱 한 가지만 짧게 한국어 한 문장으로 "
        "설명해 주세요. 색상, 모양, 크기, 질감을 전부 나열하지 마세요 — 예시들도 그중 하나만 "
        "말합니다. 보이지 않는 내용은 지어내지 마세요."
    )
